#!/usr/bin/env node
/**
 * dsh-paradise — compose `index.js` from `src/**.ts` with Node's built-in type stripper.
 *
 * COPIED FROM `dsh-observer/scripts/bundle.mjs`, deliberately and with the same contract, because
 * that script is what a working single-file bundle of THIS host looks like. Re-inventing the
 * composition is how "the build passes but the app will not boot" happens.
 *
 * Contract: index.js = HEADER + every local module reachable from src/index.ts in DEPENDENCY
 * ORDER + src/index.ts, each through Node's type stripper. Local imports are removed (the bundle
 * is one scope), `export` keywords on inlined modules are removed for the same reason, and node
 * built-in imports are hoisted and DEDUPED (two modules importing `node:fs` would otherwise
 * declare `readFileSync` twice in one scope).
 *
 * Why order is COMPUTED: an inlined module that references a later one hits a temporal-dead-zone
 * at load time, and a cycle must be a build failure rather than a runtime mystery.
 *
 * Why imports are removed by a LINE walker and not a `[\s\S]*?` regex: the loose version runs from
 * one `import` to a distant `} from './x.js'` across a template literal containing the word
 * "import" and eats half the file (the "Unterminated regexp literal" incident).
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative, resolve, dirname } from 'node:path'
import { stripTypeScriptTypes } from 'node:module'

export const BANNER = '// GENERATED from src/ by scripts/build.mjs — do not edit this file directly.\n'

const LOCAL_SINGLE_LINE = /^import[^\n]*from[ \t]+'\.[^'\n]+';?[ \t]*\n/gmu
const LOCAL_BRACKETED = /^import[ \t]*\{\n(?:[ \t]+[^\n]*\n){0,40}?\}[ \t]*from[ \t]+'\.[^'\n]+';?[ \t]*\n/gmu
const LOCAL_SINGLE_BRACKETED = /^import[ \t]*\{(?:[^}\n]*)\}[ \t]*from[ \t]+'\.[^'\n]+';?[ \t]*\n/gmu

export function removeLocalImports(source) {
  const normalized = source.replace(/\r\n/gu, '\n').replace(/\r/gu, '\n')
  return normalized
    .replace(LOCAL_SINGLE_LINE, '')
    .replace(LOCAL_SINGLE_BRACKETED, '')
    .replace(LOCAL_BRACKETED, '')
}

function resolveSpecifier(fromFile, spec) {
  const absolute = resolve(dirname(fromFile), spec)
  return absolute.endsWith('.ts') ? absolute : `${absolute.slice(0, -'.js'.length)}.ts`
}

function localSpecifiers(source) {
  const specs = []
  for (const match of source.matchAll(/from\s*['"](\.[^'"]+)['"]/gu)) specs.push(match[1])
  return specs
}

function localImportsOf(file) {
  return localSpecifiers(readFileSync(file, 'utf8')).map((spec) => resolveSpecifier(file, spec))
}

/** Depth-first topological order over the modules REACHABLE FROM src/index.ts. */
function orderModules(srcDir) {
  const indexPath = join(srcDir, 'index.ts')
  const state = new Map()
  const ordered = []
  const visit = (file, stack) => {
    if (state.get(file) === 'done') return
    if (state.get(file) === 'visiting') {
      throw new Error(`cycle in src/: ${[...stack, file].map((f) => relative(srcDir, f)).join(' -> ')}`)
    }
    state.set(file, 'visiting')
    for (const dep of localImportsOf(file)) visit(dep, [...stack, file])
    state.set(file, 'done')
    ordered.push(file)
  }
  for (const dep of localImportsOf(indexPath)) visit(dep, [indexPath])
  return ordered
}

function inline(file) {
  const source = readFileSync(file, 'utf8')
  const code = stripTypeScriptTypes(removeLocalImports(source), { mode: 'strip' })
  /**
   * A MULTI-LINE `export { … }` BECOMES A NAKED BLOCK IF ONLY THE KEYWORD IS REMOVED.
   *
   * WHY THIS USED TO BREAK, AND WHY THE BUILD DID NOT NOTICE:
   *
   *     export {
   *       createFirewall,
   *     }
   *
   * `replace(/^export\s+/gmu, '')` turns that into
   *
   *     {
   *       createFirewall,
   *     }
   *
   * which is a BLOCK STATEMENT containing a label — valid syntax right up until the trailing `}` closes
   * something it never opened, or until a second one follows. The composer's guard only looks for surviving
   * RELATIVE SPECIFIERS, so the artifact shipped and failed at `import()` time instead of at build time.
   *
   * THE FIX removes a bare re-export LIST entirely (its names are already in scope, because the module was
   * imported at the top of the file by the author). It is anchored to a line that STARTS with `export` and
   * a brace, and requires the list to be balanced — so a `export const x = {` is untouched.
   */
  const withoutBareReExportList = code.replace(/^export\s*\{[^}]*\}\s*;?[ \t]*\n/gmu, '')
  return withoutBareReExportList.replace(/^export\s+/gmu, '').trim()
}

const NODE_IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'(node:[^']+)'\s*;?[ \t]*\n?/gmu

function hoistNodeImports(pieces) {
  const byModule = new Map()
  const stripped = pieces.map((code) =>
    code.replace(NODE_IMPORT, (_whole, names, moduleName) => {
      const set = byModule.get(moduleName) ?? new Set()
      for (const name of names.split(',')) {
        const trimmed = name.trim()
        if (trimmed.length > 0) set.add(trimmed)
      }
      byModule.set(moduleName, set)
      return ''
    }),
  )
  const header = [...byModule.entries()]
    .map(([moduleName, names]) => `import { ${[...names].sort().join(', ')} } from '${moduleName}'`)
    .join('\n')
  return { header, stripped }
}

/**
 * Compose the shipped bundle for a package root.
 *
 * @param {string} root absolute package root (the directory holding `src/`)
 * @returns {{ output: string, modules: string[] }}
 */
export function composeBundle(root) {
  const srcDir = join(root, 'src')
  const ordered = orderModules(srcDir)
  const pieces = ordered.map((file) => inline(file))

  const indexSource = readFileSync(join(srcDir, 'index.ts'), 'utf8')
  pieces.push(stripTypeScriptTypes(removeLocalImports(indexSource), { mode: 'strip' }).trim())

  const names = ordered.map((file) => relative(srcDir, file).replace(/\\/gu, '/'))
  const { header: nodeHeader, stripped } = hoistNodeImports(pieces)
  const header = `${BANNER}// Inlined modules (dependency order): ${names.length === 0 ? '(none)' : names.join(', ')}\n${nodeHeader}\n`
  const output = `${header}\n${stripped.join('\n\n')}\n`

  // No relative specifier may survive into the shipped file: a single left-behind
  // `export { x } from './core/y.js'` fails at IMPORT time, and `node --check` passes.
  for (const [index, line] of output.split('\n').entries()) {
    if (/from\s*'\.\.?\//u.test(line)) {
      throw new Error(
        `bundle would ship an unresolved relative import (line ${index + 1}): ${line.trim()}\n` +
          'Hint: inlined modules must be re-exported BARE (`export { a, b }`), not `export ... from`.',
      )
    }
  }

  /**
   * THE SYNTAX GATE — added after a real incident.
   *
   * A multi-line bare re-export used to be inlined into a naked `{ … }` block. The artifact then failed at
   * `import()` time with `SyntaxError: Unexpected token '}'` — i.e. after `npm run build` had printed
   * "built", and only when something tried to load the package.
   *
   * A BUILD THAT PRODUCES AN UNPARSEABLE FILE HAS NOT SUCCEEDED. The check below is a SHAPE test, not a
   * parser: a block whose whole body is a comma-separated identifier list is the fingerprint of a
   * de-exported re-export list, and that shape cannot occur in hand-written code in this package.
   */
  const bannedBlock = /^\{[ \t]*\r?\n(?:[ \t]*[A-Za-z_$][\w$]*[ \t]*,?[ \t]*\r?\n)+[ \t]*\}[ \t]*$/mu
  if (bannedBlock.test(output)) {
    const match = bannedBlock.exec(output)
    const line = output.slice(0, match.index).split('\n').length
    throw new Error(
      `bundle contains a NAKED BLOCK that is a de-exported re-export list (line ${line}).\n` +
        'The inliner must REMOVE a multi-line `export { … }`, not strip its keyword and leave a block.\n' +
        `Offending block:\n${match[0]}`,
    )
  }

  return { output, modules: names }
}

/** Every .ts file under src/, for the "an orphan module is inert" check. */
export function listSourceFiles(root) {
  const out = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry)
      if (statSync(full).isDirectory()) walk(full)
      else if (entry.endsWith('.ts')) out.push(relative(join(root, 'src'), full).replace(/\\/gu, '/'))
    }
  }
  walk(join(root, 'src'))
  return out
}
